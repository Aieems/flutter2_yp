create policy "profiles_select_own_or_admin"
  on public.profiles for select to authenticated
  using (id = auth.uid() or public.current_role_level() >= 3);

create policy "profiles_update_own_display"
  on public.profiles for update to authenticated
  using (id = auth.uid())
  with check (id = auth.uid());

create policy "profiles_admin_update_roles"
  on public.profiles for update to authenticated
  using (public.current_role_level() >= 3)
  with check (public.current_role_level() >= 3);

create policy "categories_select_auth"
  on public.categories for select to authenticated using (true);
create policy "partners_select_auth"
  on public.partners for select to authenticated using (true);
create policy "tags_select_auth"
  on public.tags for select to authenticated using (true);
create policy "volunteers_select_auth"
  on public.volunteers for select to authenticated using (true);
create policy "projects_select_auth"
  on public.projects for select to authenticated using (true);

create policy "categories_write_coordinator"
  on public.categories for all to authenticated
  using (public.current_role_level() >= 2)
  with check (public.current_role_level() >= 2);

create policy "partners_write_coordinator"
  on public.partners for all to authenticated
  using (public.current_role_level() >= 2)
  with check (public.current_role_level() >= 2);

create policy "tags_write_coordinator"
  on public.tags for all to authenticated
  using (public.current_role_level() >= 2)
  with check (public.current_role_level() >= 2);

create policy "volunteers_write_coordinator"
  on public.volunteers for all to authenticated
  using (public.current_role_level() >= 2)
  with check (public.current_role_level() >= 2);

create policy "projects_write_coordinator"
  on public.projects for all to authenticated
