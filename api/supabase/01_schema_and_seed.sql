create or replace function public.app_role_level(role text)
returns integer
language sql
immutable
as $$
  select case role
    when 'admin' then 3
    when 'coordinator' then 2
    when 'volunteer' then 1
    else 0
  end;
$$;

create or replace function public.current_role_level()
returns integer
language sql
stable
security definer
set search_path = public
as $$
  select public.app_role_level(
    coalesce(
      (select p.role from public.profiles p where p.id = auth.uid()),
      'volunteer'
    )
  );
$$;

