create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  username text not null unique,
  display_name text not null,
  role text not null default 'volunteer'
    check (role in ('volunteer', 'coordinator', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null,
  deleted_at timestamptz
);

create table if not exists public.partners (
  id bigint generated by default as identity primary key,
  last_name text not null,
  first_name text not null,
  country text not null,
  birth_year integer not null,
  deleted_at timestamptz
);

create table if not exists public.tags (
  id bigint generated by default as identity primary key,
  name text not null,
  category_id bigint not null references public.categories (id),
  deleted_at timestamptz
);

create table if not exists public.volunteers (
  id bigint generated by default as identity primary key,
  first_name text not null,
  last_name text not null,
  email text not null unique,
  card_number text not null,
  card_issued_at timestamptz not null,
  card_expires_at timestamptz not null,
  deleted_at timestamptz
);

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  title text not null,
  code text not null unique,
  year integer not null,
  goal_amount integer not null,
  category_id bigint not null references public.categories (id),
  partner_ids bigint[] not null default '{}',
  tag_ids bigint[] not null default '{}',
  volunteers_total integer not null default 0,
  volunteers_active integer not null default 0,
  deleted_at timestamptz
);

-- ---------------------------------------------------------------------------
-- Триггер профиля при регистрации
-- ---------------------------------------------------------------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, username, display_name, role)
  values (
    new.id,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'username'), ''), split_part(new.email, '@', 1)),
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'display_name'), ''), split_part(new.email, '@', 1)),
    coalesce(nullif(new.raw_user_meta_data ->> 'role', ''), 'volunteer')
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

